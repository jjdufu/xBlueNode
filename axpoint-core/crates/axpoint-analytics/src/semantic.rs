fn run_guarded_conn(
    conn: &duckdb::Connection,
    catalog: &TenantCatalog,
    guarded: &GuardedSql,
    opts: MetricExecuteOptions,
) -> Result<QueryResult, AppError> {
    let started = Instant::now();
    let mut stmt = conn
        .prepare(&guarded.sql)
        .map_err(|err| AppError::Database(format!("metric prepare failed: {err}")))?;
    let stream = stmt
        .query_arrow([])
        .map_err(|err| AppError::Database(format!("metric execution failed: {err}")))?;
    let schema = stream.get_schema();
    let batches: Vec<RecordBatch> = stream.collect();
    let duration_ms = u64::try_from(started.elapsed().as_millis()).unwrap_or(u64::MAX);

    let out = batches_to_query_result(
        &schema,
        &batches,
        ResultSerializeOptions {
            effective_max_rows: guarded.effective_max_rows,
            sql: guarded.sql.clone(),
            duration_ms,
            reveal_pii: opts.reveal_pii,
            has_pii_raw_read: opts.has_pii_raw_read,
            catalog,
            guarded,
        },
    )?;
    Ok(out.result)
}

fn is_valid_metric_ident(name: &str) -> bool {
    let bytes = name.as_bytes();
    if bytes.is_empty() || bytes.len() > 63 {
        return false;
    }
    let Some(&first) = bytes.first() else {
        return false;
    };
    if !first.is_ascii_lowercase() {
        return false;
    }
    bytes
        .iter()
        .all(|&b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
}

fn resolve_requested_dims(
    metric: &MetricDef,
    dataset: &CatalogDatasetEntry,
    requested: &[String],
) -> Result<Vec<ResolvedMetricDim>, AppError> {
    let mut seen = BTreeSet::new();
    let mut out = Vec::with_capacity(requested.len());
    for raw in requested {
        let key = raw.trim();
        if key.is_empty() {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                "dimension name cannot be empty",
            ));
        }
        let matched = metric
            .dimensions
            .iter()
            .find(|d| d.name.eq_ignore_ascii_case(key))
            .or_else(|| {
                metric
                    .dimensions
                    .iter()
                    .find(|d| d.column.eq_ignore_ascii_case(key))
            });
        let Some(decl) = matched else {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!(
                    "dimension '{key}' is not declared on metric '{}'",
                    metric.name
                ),
            ));
        };
        if !seen.insert(decl.name.to_ascii_lowercase()) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!("duplicate dimension '{}' in metric query", decl.name),
            ));
        }
        let Some(col_meta) = dataset
            .columns
            .get(&decl.column.trim().to_ascii_lowercase())
        else {
            return Err(AppError::Conflict("SCHEMA_BREAKING_CHANGE"));
        };
        out.push(ResolvedMetricDim {
            output_name: decl.name.clone(),
            physical_col: col_meta.column_name.clone(),
        });
    }
    Ok(out)
}

fn resolve_filter_col_for_metric(
    metric: &MetricDef,
    dataset: &CatalogDatasetEntry,
    field: &str,
) -> Result<String, AppError> {
    let trimmed = field.trim();
    if trimmed.is_empty() {
        return Err(AppError::bad("INVALID_ARGUMENT", "filter field is empty"));
    }
    if let Some(decl) = metric
        .dimensions
        .iter()
        .find(|d| d.name.eq_ignore_ascii_case(trimmed))
        && let Some(meta) = dataset
            .columns
            .get(&decl.column.trim().to_ascii_lowercase())
    {
        return Ok(meta.column_name.clone());
    }
    if let Some(meta) = dataset.columns.get(&trimmed.to_ascii_lowercase()) {
        return Ok(meta.column_name.clone());
    }
    Err(AppError::bad(
        "INVALID_ARGUMENT",
        format!(
            "unknown filter column '{trimmed}' for metric '{}' on dataset '{}'",
            metric.name, dataset.name
        ),
    ))
}

fn resolve_metric_time_col(
    metric: &MetricDef,
    dataset: &CatalogDatasetEntry,
) -> Result<Option<(String, DataType)>, AppError> {
    let Some(tc_raw) = metric
        .time_column
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    else {
        return Ok(None);
    };
    let Some(meta) = dataset.columns.get(&tc_raw.to_ascii_lowercase()) else {
        return Err(AppError::Conflict("SCHEMA_BREAKING_CHANGE"));
    };
    if !matches!(meta.data_type, DataType::Date | DataType::Timestamp) {
        return Err(AppError::Conflict("SCHEMA_BREAKING_CHANGE"));
    }
    Ok(Some((meta.column_name.clone(), meta.data_type)))
}

fn append_time_range_predicates(
    tc_col: &str,
    _tc_dt: DataType,
    tr: &MetricTimeRange,
    where_parts: &mut Vec<String>,
    params: &mut BTreeMap<String, serde_json::Value>,
) {
    let tc_q = quote_ident(tc_col);
    let from_naive = tr
        .from
        .naive_utc()
        .format("%Y-%m-%d %H:%M:%S%.f")
        .to_string();
    let to_naive = tr.to.naive_utc().format("%Y-%m-%d %H:%M:%S%.f").to_string();
    params.insert(
        String::from("__tr_from"),
        serde_json::Value::String(from_naive),
    );
    params.insert(String::from("__tr_to"), serde_json::Value::String(to_naive));
    where_parts.push(format!(
        "CAST({tc_q} AS TIMESTAMP) >= CAST(:__tr_from AS TIMESTAMP)"
    ));
    where_parts.push(format!(
        "CAST({tc_q} AS TIMESTAMP) < CAST(:__tr_to AS TIMESTAMP)"
    ));
}

#[derive(Debug, Clone)]
enum PeriodShiftKind {
    Months(u32),
    Duration(ChronoDuration),
}

#[derive(Debug, Clone)]
struct RangeShiftPlan {
    shifted_range: MetricTimeRange,
    shift_kind: PeriodShiftKind,
    grain: RollupGrain,
}

fn compute_range_shift(
    tr: &MetricTimeRange,
    mode: MetricCompareMode,
    grain: RollupGrain,
) -> Result<RangeShiftPlan, AppError> {
    if tr.to <= tr.from {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            "time_range.to must be greater than time_range.from",
        ));
    }
    match mode {
        MetricCompareMode::SamePeriodLastYear => {
            let months_12 = Months::new(12);
            let from = tr.from.checked_sub_months(months_12).ok_or_else(|| {
                AppError::bad("INVALID_ARGUMENT", "time_range.from out of calendar bounds")
            })?;
            let to = tr.to.checked_sub_months(months_12).ok_or_else(|| {
                AppError::bad("INVALID_ARGUMENT", "time_range.to out of calendar bounds")
            })?;
            Ok(RangeShiftPlan {
                shifted_range: MetricTimeRange { from, to },
                shift_kind: PeriodShiftKind::Months(12),
                grain,
            })
        }
        MetricCompareMode::PreviousPeriod => {
            if let Some(exact_months) = exact_calendar_month_span(tr.from, tr.to) {
                let m = Months::new(exact_months);
                let prev_from = tr.from.checked_sub_months(m).ok_or_else(|| {
                    AppError::bad("INVALID_ARGUMENT", "time_range.from out of calendar bounds")
                })?;
                return Ok(RangeShiftPlan {
                    shifted_range: MetricTimeRange {
                        from: prev_from,
                        to: tr.from,
                    },
                    shift_kind: PeriodShiftKind::Months(exact_months),
                    grain,
                });
            }
            let dur = tr.to.signed_duration_since(tr.from);
            let prev_from = tr
                .from
                .checked_sub_signed(dur)
                .ok_or_else(|| AppError::bad("INVALID_ARGUMENT", "time_range underflow"))?;
            Ok(RangeShiftPlan {
                shifted_range: MetricTimeRange {
                    from: prev_from,
                    to: tr.from,
                },
                shift_kind: PeriodShiftKind::Duration(dur),
                grain,
            })
        }
    }
}

fn exact_calendar_month_span(from: DateTime<Utc>, to: DateTime<Utc>) -> Option<u32> {
    if from.day() != 1
        || to.day() != 1
        || from.hour() != 0
        || from.minute() != 0
        || from.second() != 0
        || from.nanosecond() != 0
        || to.hour() != 0
        || to.minute() != 0
        || to.second() != 0
        || to.nanosecond() != 0
    {
        return None;
    }
    let total_from = i64::from(from.year()) * 12 + i64::from(from.month0());
    let total_to = i64::from(to.year()) * 12 + i64::from(to.month0());
    let diff = total_to.checked_sub(total_from)?;
    if diff <= 0 {
        return None;
    }
    u32::try_from(diff).ok()
}

fn merge_compared_results(
    metric_name: &str,
    compiled: &CompiledMetricQuery,
    primary: &QueryResult,
    shifted_opt: Option<(&QueryResult, &RangeShiftPlan)>,
    mode: MetricCompareMode,
) -> MetricQueryResult {
    let grain = compiled.effective_grain.unwrap_or(RollupGrain::Day);

    let mut compare_lookup: HashMap<Vec<String>, serde_json::Value> = HashMap::new();
    if let Some((cmp_qr, shift_plan)) = shifted_opt {
        for row in &cmp_qr.rows {
            if let Some(aligned_key) = build_shifted_forward_key(row, compiled, shift_plan) {
                let val = row.get("value").cloned().unwrap_or(serde_json::Value::Null);
                compare_lookup.insert(aligned_key, val);
            }
        }
    } else {
        for row in &primary.rows {
            if let Some(raw_key) = build_normalized_row_key(row, compiled, grain) {
                let val = row.get("value").cloned().unwrap_or(serde_json::Value::Null);
                compare_lookup.insert(raw_key, val);
            }
        }
    }

    let mut columns = primary.columns.clone();
    for extra in ["compare_value", "delta", "delta_ratio"] {
        columns.push(QueryColumn {
            name: String::from(extra),
            data_type: DataType::Float64,
            pii_category: PiiCategory::None,
            masked: false,
        });
    }

    let mut out_rows = Vec::with_capacity(primary.rows.len());
    for row in &primary.rows {
        let mut merged = row.clone();
        let cur_val = row.get("value").cloned().unwrap_or(serde_json::Value::Null);

        let lookup_key = if shifted_opt.is_some() {
            build_normalized_row_key(row, compiled, grain)
        } else {
            build_self_lag_lookup_key(row, compiled, grain, mode)
        };

        let cmp_val = lookup_key
            .and_then(|k| compare_lookup.get(&k).cloned())
            .unwrap_or(serde_json::Value::Null);

        let (delta_val, ratio_val) = compute_delta_and_ratio(&cur_val, &cmp_val);
        merged.insert(String::from("compare_value"), cmp_val);
        merged.insert(String::from("delta"), delta_val);
        merged.insert(String::from("delta_ratio"), ratio_val);
        out_rows.push(merged);
    }

    let (combined_sql, total_ms) = if let Some((cmp_qr, _)) = shifted_opt {
        (
            format!("{}; {}", primary.sql, cmp_qr.sql),
            primary.duration_ms.saturating_add(cmp_qr.duration_ms),
        )
    } else {
        (primary.sql.clone(), primary.duration_ms)
    };

    MetricQueryResult {
        metrics: vec![String::from(metric_name)],
        columns,
        rows: out_rows,
        sql: combined_sql,
        duration_ms: total_ms,
    }
}

fn build_normalized_row_key(
    row: &serde_json::Map<String, serde_json::Value>,
    compiled: &CompiledMetricQuery,
    grain: RollupGrain,
) -> Option<Vec<String>> {
    let mut key = Vec::with_capacity(compiled.dim_names.len().saturating_add(1));
    if compiled.has_period {
        let p_val = row.get("period")?;
        let dt = parse_period_utc(p_val)?;
        let bucket = truncate_utc_to_grain(dt, grain);
        key.push(bucket.to_rfc3339_opts(SecondsFormat::Secs, true));
    }
    for d_name in &compiled.dim_names {
        let v = row.get(d_name).map_or_else(String::new, json_key_str);
        key.push(v);
    }
    Some(key)
}

fn build_shifted_forward_key(
    cmp_row: &serde_json::Map<String, serde_json::Value>,
    compiled: &CompiledMetricQuery,
    plan: &RangeShiftPlan,
) -> Option<Vec<String>> {
    let mut key = Vec::with_capacity(compiled.dim_names.len().saturating_add(1));
    if compiled.has_period {
        let p_val = cmp_row.get("period")?;
        let dt = parse_period_utc(p_val)?;
        let shifted = match plan.shift_kind {
            PeriodShiftKind::Months(m) => dt.checked_add_months(Months::new(m))?,
            PeriodShiftKind::Duration(dur) => dt.checked_add_signed(dur)?,
        };
        let bucket = truncate_utc_to_grain(shifted, plan.grain);
        key.push(bucket.to_rfc3339_opts(SecondsFormat::Secs, true));
    }
    for d_name in &compiled.dim_names {
        let v = cmp_row.get(d_name).map_or_else(String::new, json_key_str);
        key.push(v);
    }
    Some(key)
}

fn build_self_lag_lookup_key(
    row: &serde_json::Map<String, serde_json::Value>,
    compiled: &CompiledMetricQuery,
    grain: RollupGrain,
    mode: MetricCompareMode,
) -> Option<Vec<String>> {
    if !compiled.has_period {
        return None;
    }
    let p_val = row.get("period")?;
    let dt = parse_period_utc(p_val)?;
    let prev_dt = match mode {
        MetricCompareMode::SamePeriodLastYear => dt.checked_sub_months(Months::new(12))?,
        MetricCompareMode::PreviousPeriod => match grain {
            RollupGrain::Month => dt.checked_sub_months(Months::new(1))?,
            RollupGrain::Day => dt.checked_sub_signed(ChronoDuration::days(1))?,
            RollupGrain::Hour => dt.checked_sub_signed(ChronoDuration::hours(1))?,
            RollupGrain::Minute => dt.checked_sub_signed(ChronoDuration::minutes(1))?,
        },
    };
    let bucket = truncate_utc_to_grain(prev_dt, grain);
    let mut key = Vec::with_capacity(compiled.dim_names.len().saturating_add(1));
    key.push(bucket.to_rfc3339_opts(SecondsFormat::Secs, true));
    for d_name in &compiled.dim_names {
        let v = row.get(d_name).map_or_else(String::new, json_key_str);
        key.push(v);
    }
    Some(key)
}

fn compute_delta_and_ratio(
    cur_val: &serde_json::Value,
    cmp_val: &serde_json::Value,
) -> (serde_json::Value, serde_json::Value) {
    let (Some(cur), Some(cmp)) = (json_num_f64(cur_val), json_num_f64(cmp_val)) else {
        return (serde_json::Value::Null, serde_json::Value::Null);
    };
    let delta = round_clean_f64(cur - cmp);
    let delta_json = serde_json::Number::from_f64(delta)
        .map_or(serde_json::Value::Null, serde_json::Value::Number);
    if cmp == 0.0 {
        return (delta_json, serde_json::Value::Null);
    }
    let ratio = round_clean_f64((cur - cmp) / cmp);
    let ratio_json = if ratio.is_finite() {
        serde_json::Number::from_f64(ratio)
            .map_or(serde_json::Value::Null, serde_json::Value::Number)
    } else {
        serde_json::Value::Null
    };
    (delta_json, ratio_json)
}

fn round_clean_f64(v: f64) -> f64 {
    if v == 0.0 {
        return 0.0;
    }
    let scaled = v * 1_000_000_000_000.0;
    if scaled.is_finite() {
        scaled.round() / 1_000_000_000_000.0
    } else {
        v
    }
}

fn parse_period_utc(val: &serde_json::Value) -> Option<DateTime<Utc>> {
    let s = val.as_str()?.trim();
    if let Ok(dt) = DateTime::parse_from_rfc3339(s) {
        return Some(dt.with_timezone(&Utc));
    }
    if let Ok(d) = NaiveDate::parse_from_str(s, "%Y-%m-%d") {
        return d.and_hms_opt(0, 0, 0).map(|ndt| ndt.and_utc());
    }
    if let Ok(ndt) = chrono::NaiveDateTime::parse_from_str(s, "%Y-%m-%d %H:%M:%S") {
        return Some(ndt.and_utc());
    }
    None
}

fn truncate_utc_to_grain(dt: DateTime<Utc>, grain: RollupGrain) -> DateTime<Utc> {
    match grain {
        RollupGrain::Month => NaiveDate::from_ymd_opt(dt.year(), dt.month(), 1)
            .and_then(|d| d.and_hms_opt(0, 0, 0))
            .map_or(dt, |ndt| ndt.and_utc()),
        RollupGrain::Day => dt
            .date_naive()
            .and_hms_opt(0, 0, 0)
            .map_or(dt, |ndt| ndt.and_utc()),
        RollupGrain::Hour => dt
            .date_naive()
            .and_hms_opt(dt.hour(), 0, 0)
            .map_or(dt, |ndt| ndt.and_utc()),
        RollupGrain::Minute => dt
            .date_naive()
            .and_hms_opt(dt.hour(), dt.minute(), 0)
            .map_or(dt, |ndt| ndt.and_utc()),
    }
}

fn json_num_f64(val: &serde_json::Value) -> Option<f64> {
    match val {
        serde_json::Value::Number(n) => n.as_f64().filter(|f| f.is_finite()),
        serde_json::Value::String(s) => s.trim().parse::<f64>().ok().filter(|f| f.is_finite()),
        _ => None,
    }
}

fn json_key_str(val: &serde_json::Value) -> String {
    match val {
        serde_json::Value::Null => String::new(),
        serde_json::Value::String(s) => s.clone(),
        serde_json::Value::Bool(b) => b.to_string(),
        serde_json::Value::Number(n) => n.to_string(),
        other => other.to_string(),
    }
}

fn select_multi_metrics(
    available_metrics: &[MetricDef],
    requested_names: &[String],
    catalog: &TenantCatalog,
) -> Result<Vec<MetricDef>, AppError> {
    if requested_names.is_empty() || requested_names.len() > MAX_MULTI_METRICS {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            format!("metric_names must contain 1..={MAX_MULTI_METRICS} metrics"),
        ));
    }
    let mut by_name: HashMap<String, &MetricDef> = HashMap::with_capacity(available_metrics.len());
    for m in available_metrics {
        by_name.insert(m.name.to_ascii_lowercase(), m);
    }

    let mut seen = BTreeSet::new();
    let mut out = Vec::with_capacity(requested_names.len());
    for name in requested_names {
        let lower = name.trim().to_ascii_lowercase();
        if lower.is_empty() {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                "metric_names cannot contain empty strings",
            ));
        }
        if !seen.insert(lower.clone()) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!("duplicate metric '{name}' in query-multi"),
            ));
        }
        let Some(&metric) = by_name.get(&lower) else {
            return Err(AppError::NotFound("NOT_FOUND"));
        };
        let _ = check_metric_compatibility(metric, catalog)?;
        out.push(metric.clone());
    }
    Ok(out)
}

struct AttachFilterVisitor {
    filter_expr: Expr,
    agg_depth: usize,
}

impl VisitorMut for AttachFilterVisitor {
    type Break = ();

    fn pre_visit_expr(&mut self, expr: &mut Expr) -> ControlFlow<Self::Break> {
        if let Expr::Function(func) = expr
            && is_agg_ast_function(func)
        {
            if self.agg_depth == 0 {
                attach_filter_to_function(func, &self.filter_expr);
            }
            self.agg_depth = self.agg_depth.saturating_add(1);
        }
        ControlFlow::Continue(())
    }

    fn post_visit_expr(&mut self, expr: &mut Expr) -> ControlFlow<Self::Break> {
        if let Expr::Function(func) = expr
            && is_agg_ast_function(func)
        {
            self.agg_depth = self.agg_depth.saturating_sub(1);
        }
        ControlFlow::Continue(())
    }
}

fn is_agg_ast_function(func: &Function) -> bool {
    let name = func.name.to_string();
    is_aggregate_function_name(&name)
}

fn attach_filter_to_function(func: &mut Function, extra_filter: &Expr) {
    match func.filter.take() {
        Some(existing) => {
            func.filter = Some(Box::new(Expr::BinaryOp {
                left: Box::new(Expr::Nested(existing)),
                op: BinaryOperator::And,
                right: Box::new(Expr::Nested(Box::new(extra_filter.clone()))),
            }));
        }
        None => {
            func.filter = Some(Box::new(extra_filter.clone()));
        }
    }
}

fn try_compile_same_dataset_multi(
    metrics: &[MetricDef],
    query: &MultiMetricQuery,
    catalog: &TenantCatalog,
) -> Result<Option<GuardedSql>, AppError> {
    let Some(first) = metrics.first() else {
        return Ok(None);
    };
    if !metrics.iter().all(|m| m.dataset_id == first.dataset_id) {
        return Ok(None);
    }

    let dataset = check_metric_compatibility(first, catalog)?;
    let Some((first_tc, first_dims)) =
        verify_compatible_multi_layout(metrics, dataset, &query.dimensions)?
    else {
        return Ok(None);
    };

    if first_tc.is_none() && query.time_range.is_some() {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            "metrics have no time_column for time_range",
        ));
    }

    let (projections, has_period) =
        build_multi_projections(metrics, first, query.grain, first_tc.as_ref(), &first_dims)?;

    let mut params = BTreeMap::new();
    let mut where_parts = Vec::new();
    if let Some(ref tr) = query.time_range {
        if tr.to <= tr.from {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                "time_range.to must be greater than time_range.from",
            ));
        }
        if let Some((ref tc_col, tc_dt)) = first_tc {
            append_time_range_predicates(tc_col, tc_dt, tr, &mut where_parts, &mut params);
        }
    }
    let shared_filters = compile_filters_with_resolver(
        &query.filters,
        "__mmf",
        |f| resolve_filter_col_for_metric(first, dataset, f),
        &mut params,
    )?;
    where_parts.extend(shared_filters);

    let where_sql = if where_parts.is_empty() {
        String::new()
    } else {
        format!(" WHERE {}", where_parts.join(" AND "))
    };
    let group_order_sql = build_metric_group_order(has_period, &first_dims);
    let raw_sql = format!(
        "SELECT {} FROM {}{}{}",
        projections.join(", "),
        quote_ident(&dataset.name),
        where_sql,
        group_order_sql
    );

    let guarded = guard(
        &raw_sql,
        catalog,
        &GuardOptions {
            max_rows: HARD_MAX_ROWS,
            allow_live: false,
            params,
        },
    )?;
    Ok(Some(guarded))
}

type SharedMultiLayout = (Option<(String, DataType)>, Vec<ResolvedMetricDim>);

fn verify_compatible_multi_layout(
    metrics: &[MetricDef],
    dataset: &CatalogDatasetEntry,
    requested_dims: &[String],
) -> Result<Option<SharedMultiLayout>, AppError> {
    let Some(first) = metrics.first() else {
        return Ok(None);
    };
    let first_tc = resolve_metric_time_col(first, dataset)?;
    let first_dims = resolve_requested_dims(first, dataset, requested_dims)?;

    for m in metrics.iter().skip(1) {
        let tc = resolve_metric_time_col(m, dataset)?;
        let same_tc = match (&first_tc, &tc) {
            (None, None) => true,
            (Some((a, _)), Some((b, _))) => a.eq_ignore_ascii_case(b),
            _ => false,
        };
        if !same_tc {
            return Ok(None);
        }
        let dims = resolve_requested_dims(m, dataset, requested_dims)?;
        for (da, db) in first_dims.iter().zip(dims.iter()) {
            if !da.physical_col.eq_ignore_ascii_case(&db.physical_col) {
                return Ok(None);
            }
        }
    }
    Ok(Some((first_tc, first_dims)))
}

fn build_multi_projections(
    metrics: &[MetricDef],
    first: &MetricDef,
    requested_grain: Option<RollupGrain>,
    first_tc: Option<&(String, DataType)>,
    first_dims: &[ResolvedMetricDim],
) -> Result<(Vec<String>, bool), AppError> {
    let mut projections = Vec::new();
    let has_period = if let Some((tc_col, _)) = first_tc {
        let grain = requested_grain.unwrap_or(first.default_grain);
        projections.push(format!(
            "date_trunc('{}', CAST({} AS TIMESTAMP)) AS \"period\"",
            rollup_grain_sql(grain),
            quote_ident(tc_col)
        ));
        true
    } else {
        false
    };

    for d in first_dims {
        projections.push(format!(
            "{} AS {}",
            quote_ident(&d.physical_col),
            quote_ident(&d.output_name)
        ));
    }

    for m in metrics {
        let (mut expr_ast, _, _) = inspect_sql_expression(&m.expression, true)?;
        let f_trim = m.filter_sql.trim();
        if !f_trim.is_empty() {
            let (f_ast, _, _) = inspect_sql_expression(f_trim, true)?;
            let mut attacher = AttachFilterVisitor {
                filter_expr: f_ast,
                agg_depth: 0,
            };
            let _visit_flow = VisitMut::visit(&mut expr_ast, &mut attacher);
        }
        projections.push(format!("({expr_ast}) AS {}", quote_ident(&m.name)));
    }
    Ok((projections, has_period))
}

fn outer_join_metric_results(
    per_metric: &[(String, MetricQueryResult)],
    requested_dims: &[String],
    has_compare: bool,
) -> MetricQueryResult {
    let any_has_period = per_metric
        .iter()
        .any(|(_, res)| res.columns.iter().any(|c| c.name == "period"));

    let canonical_dims = extract_canonical_dims(per_metric, requested_dims);
    let columns =
        build_outer_join_columns(per_metric, &canonical_dims, any_has_period, has_compare);

    let mut merged_rows: BTreeMap<Vec<String>, serde_json::Map<String, serde_json::Value>> =
        BTreeMap::new();
    let mut sql_parts = Vec::with_capacity(per_metric.len());
    let mut total_duration: u64 = 0;

    for (m_name, res) in per_metric {
        sql_parts.push(res.sql.clone());
        total_duration = total_duration.saturating_add(res.duration_ms);
        for row in &res.rows {
            merge_single_metric_row(
                row,
                m_name,
                per_metric,
                &canonical_dims,
                any_has_period,
                has_compare,
                &mut merged_rows,
            );
        }
    }

    MetricQueryResult {
        metrics: per_metric.iter().map(|(m, _)| m.clone()).collect(),
        columns,
        rows: merged_rows.into_values().collect(),
        sql: sql_parts.join("; "),
        duration_ms: total_duration,
    }
}

fn extract_canonical_dims(
    per_metric: &[(String, MetricQueryResult)],
    requested_dims: &[String],
) -> Vec<String> {
    let Some((_, first_res)) = per_metric.first() else {
        return requested_dims.to_vec();
    };
    first_res
        .columns
        .iter()
        .map(|c| c.name.clone())
        .filter(|n| {
            n != "period"
                && n != "value"
                && n != "compare_value"
                && n != "delta"
                && n != "delta_ratio"
        })
        .collect()
}

fn build_outer_join_columns(
    per_metric: &[(String, MetricQueryResult)],
    canonical_dims: &[String],
    any_has_period: bool,
    has_compare: bool,
) -> Vec<QueryColumn> {
    let mut columns = Vec::new();
    if any_has_period {
        columns.push(QueryColumn {
            name: String::from("period"),
            data_type: DataType::Timestamp,
            pii_category: PiiCategory::None,
            masked: false,
        });
    }
    if let Some((_, first_res)) = per_metric.first() {
        for dim_name in canonical_dims {
            if let Some(col_desc) = first_res.columns.iter().find(|c| &c.name == dim_name) {
                columns.push(col_desc.clone());
            } else {
                columns.push(QueryColumn {
                    name: dim_name.clone(),
                    data_type: DataType::String,
                    pii_category: PiiCategory::None,
                    masked: false,
                });
            }
        }
    }
    for (m_name, _) in per_metric {
        columns.push(QueryColumn {
            name: m_name.clone(),
            data_type: DataType::Float64,
            pii_category: PiiCategory::None,
            masked: false,
        });
        if has_compare {
            for suffix in ["compare_value", "delta", "delta_ratio"] {
                columns.push(QueryColumn {
                    name: format!("{m_name}_{suffix}"),
                    data_type: DataType::Float64,
                    pii_category: PiiCategory::None,
                    masked: false,
                });
            }
        }
    }
    columns
}

fn merge_single_metric_row(
    row: &serde_json::Map<String, serde_json::Value>,
    m_name: &str,
    per_metric: &[(String, MetricQueryResult)],
    canonical_dims: &[String],
    any_has_period: bool,
    has_compare: bool,
    merged_rows: &mut BTreeMap<Vec<String>, serde_json::Map<String, serde_json::Value>>,
) {
    let mut join_key = Vec::with_capacity(canonical_dims.len().saturating_add(1));
    let mut normalized_period_json = serde_json::Value::Null;
    if any_has_period {
        if let Some(pv) = row.get("period") {
            if let Some(dt) = parse_period_utc(pv) {
                let iso = dt.to_rfc3339_opts(SecondsFormat::Secs, true);
                join_key.push(iso.clone());
                normalized_period_json = serde_json::Value::String(iso);
            } else {
                join_key.push(json_key_str(pv));
                normalized_period_json = pv.clone();
            }
        } else {
            join_key.push(String::new());
        }
    }
    for dim_name in canonical_dims {
        join_key.push(row.get(dim_name).map_or_else(String::new, json_key_str));
    }

    let entry = merged_rows.entry(join_key).or_insert_with(|| {
        let mut base = serde_json::Map::new();
        if any_has_period {
            base.insert(String::from("period"), normalized_period_json);
        }
        for dim_name in canonical_dims {
            let v = row
                .get(dim_name)
                .cloned()
                .unwrap_or(serde_json::Value::Null);
            base.insert(dim_name.clone(), v);
        }
        for (other_m, _) in per_metric {
            base.insert(other_m.clone(), serde_json::Value::Null);
            if has_compare {
                for suffix in ["compare_value", "delta", "delta_ratio"] {
                    base.insert(format!("{other_m}_{suffix}"), serde_json::Value::Null);
                }
            }
        }
        base
    });

    let val = row.get("value").cloned().unwrap_or(serde_json::Value::Null);
    entry.insert(String::from(m_name), val);
    if has_compare {
        for suffix in ["compare_value", "delta", "delta_ratio"] {
            let cv = row.get(suffix).cloned().unwrap_or(serde_json::Value::Null);
            entry.insert(format!("{m_name}_{suffix}"), cv);
        }
    }
}
