/// Execution options for [`execute_metric_query`] and [`execute_multi_metric_query`].
#[derive(Debug, Clone, Copy, Default)]
pub struct MetricExecuteOptions {
    /// Optional execution timeout in milliseconds.
    pub timeout_ms: Option<u64>,
    /// Whether raw PII values are requested.
    pub reveal_pii: bool,
    /// Whether caller holds `Permission::PiiRawRead`.
    pub has_pii_raw_read: bool,
}

/// Validated and guarded SQL plan compiled from a single [`MetricDef`] + [`MetricQuery`].
#[derive(Debug, Clone)]
pub struct CompiledMetricQuery {
    /// Unrewritten SQL generated by the semantic compiler.
    pub raw_sql: String,
    /// Guarded SQL ready for `DuckDB` execution.
    pub guarded: GuardedSql,
    /// `true` when output includes a leading `period` bucket column.
    pub has_period: bool,
    /// Effective time grain when `has_period == true`.
    pub effective_grain: Option<RollupGrain>,
    /// Output dimension names in projection order.
    pub dim_names: Vec<String>,
}

#[derive(Debug, Clone)]
struct ResolvedMetricDim {
    output_name: String,
    physical_col: String,
}

/// Returns `true` if `func_name` is a recognized `DuckDB` aggregate function (`05-STEP04` §04.5.1).
#[must_use]
pub fn is_aggregate_function_name(func_name: &str) -> bool {
    let lower = func_name.trim().to_ascii_lowercase();
    ALLOWED_AGGREGATE_FUNCTIONS.contains(&lower.as_str())
}

/// Validates a [`CreateMetricRequest`] against `catalog`, returning the backing dataset's
/// current `schema_version` on success (`05-STEP04` §04.5.1).
///
/// # Errors
/// - Returns `AppError::NotFound("DATASET_NOT_FOUND")` if `req.dataset_id` is not in `catalog`.
/// - Returns `AppError::BadRequest` (`INVALID_ARGUMENT` or `SQL_REJECTED`) if identifier format,
///   aggregate expression, `filter_sql`, `dimensions`, or `time_column` validation fails.
pub fn validate_create_metric_request(
    req: &CreateMetricRequest,
    catalog: &TenantCatalog,
) -> Result<i32, AppError> {
    if !is_valid_metric_ident(&req.name) {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            format!(
                "metric name '{}' must match ^[a-z][a-z0-9_]{{0,62}}$",
                req.name
            ),
        ));
    }
    if req.display_name.trim().is_empty() {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            "metric display_name cannot be empty",
        ));
    }
    let Some(dataset) = catalog.dataset_by_id(req.dataset_id) else {
        return Err(AppError::NotFound("DATASET_NOT_FOUND"));
    };

    validate_metric_components(
        &req.expression,
        &req.filter_sql,
        req.time_column.as_deref(),
        &req.dimensions,
        dataset,
    )?;
    Ok(dataset.schema_version)
}

/// Validates a persisted or candidate [`MetricDef`] against `catalog` (`05-STEP04` §04.5.1).
///
/// # Errors
/// Returns `DATASET_NOT_FOUND`, `INVALID_ARGUMENT`, or `SQL_REJECTED` if validation fails.
pub fn validate_metric_def(metric: &MetricDef, catalog: &TenantCatalog) -> Result<(), AppError> {
    if !is_valid_metric_ident(&metric.name) {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            format!(
                "metric name '{}' must match ^[a-z][a-z0-9_]{{0,62}}$",
                metric.name
            ),
        ));
    }
    let Some(dataset) = catalog.dataset_by_id(metric.dataset_id) else {
        return Err(AppError::NotFound("DATASET_NOT_FOUND"));
    };
    validate_metric_components(
        &metric.expression,
        &metric.filter_sql,
        metric.time_column.as_deref(),
        &metric.dimensions,
        dataset,
    )
}

fn validate_metric_components(
    expression: &str,
    filter_sql: &str,
    time_column: Option<&str>,
    dimensions: &[MetricDimension],
    dataset: &CatalogDatasetEntry,
) -> Result<(), AppError> {
    let (_expr_ast, expr_cols, expr_funcs) = inspect_sql_expression(expression, true)?;
    if !expr_funcs.iter().any(|f| is_aggregate_function_name(f)) {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            "metric expression must contain at least one aggregate function",
        ));
    }
    for col in &expr_cols {
        if !dataset.columns.contains_key(col) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!(
                    "metric expression references unknown column '{col}' in dataset '{}'",
                    dataset.name
                ),
            ));
        }
    }

    let trimmed_filter = filter_sql.trim();
    if !trimmed_filter.is_empty() {
        let (_f_ast, filter_cols, filter_funcs) = inspect_sql_expression(trimmed_filter, true)?;
        if filter_funcs.iter().any(|f| is_aggregate_function_name(f)) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                "metric filter_sql cannot contain aggregate functions",
            ));
        }
        for col in &filter_cols {
            if !dataset.columns.contains_key(col) {
                return Err(AppError::bad(
                    "INVALID_ARGUMENT",
                    format!(
                        "metric filter_sql references unknown column '{col}' in dataset '{}'",
                        dataset.name
                    ),
                ));
            }
        }
    }

    let mut seen_dim_names = BTreeSet::new();
    for dim in dimensions {
        let d_name = dim.name.trim();
        let d_col = dim.column.trim();
        if !is_valid_metric_ident(d_name) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!("invalid metric dimension name '{d_name}'"),
            ));
        }
        if !seen_dim_names.insert(d_name.to_ascii_lowercase()) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!("duplicate metric dimension name '{d_name}'"),
            ));
        }
        if !dataset.columns.contains_key(&d_col.to_ascii_lowercase()) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!(
                    "dimension '{d_name}' references unknown column '{d_col}' in dataset '{}'",
                    dataset.name
                ),
            ));
        }
    }

    if let Some(tc_raw) = time_column.map(str::trim).filter(|s| !s.is_empty()) {
        let Some(meta) = dataset.columns.get(&tc_raw.to_ascii_lowercase()) else {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!(
                    "time_column '{tc_raw}' does not exist in dataset '{}'",
                    dataset.name
                ),
            ));
        };
        if !matches!(meta.data_type, DataType::Date | DataType::Timestamp) {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                format!(
                    "time_column '{tc_raw}' must have DATE or TIMESTAMP type, got {}",
                    meta.data_type
                ),
            ));
        }
    }

    Ok(())
}

/// Returns `true` if `metric` is incompatible with `dataset`'s current schema (`05-STEP04` §04.5.1).
#[must_use]
pub fn is_metric_broken_for_dataset(metric: &MetricDef, dataset: &CatalogDatasetEntry) -> bool {
    if metric.broken {
        return true;
    }
    validate_metric_components(
        &metric.expression,
        &metric.filter_sql,
        metric.time_column.as_deref(),
        &metric.dimensions,
        dataset,
    )
    .is_err()
}

/// Returns `true` if `metric`'s backing dataset is missing or any referenced column disappeared
/// or changed to an incompatible type (`05-STEP04` §04.5.1).
#[must_use]
pub fn is_metric_broken(metric: &MetricDef, catalog: &TenantCatalog) -> bool {
    if metric.broken {
        return true;
    }
    let Some(dataset) = catalog.dataset_by_id(metric.dataset_id) else {
        return true;
    };
    is_metric_broken_for_dataset(metric, dataset)
}

/// Verifies that `metric` is still compatible with its backing dataset's current schema, returning
/// `AppError::Conflict("SCHEMA_BREAKING_CHANGE")` (`HTTP 409`) if broken (`05-STEP04` §04.5.1).
///
/// # Errors
/// - Returns `AppError::Conflict("SCHEMA_BREAKING_CHANGE")` if `metric` is marked broken or any
///   referenced column / `time_column` type is incompatible with the current dataset schema.
/// - Returns `AppError::NotFound("DATASET_NOT_FOUND")` if the backing dataset is absent.
pub fn check_metric_compatibility<'a>(
    metric: &MetricDef,
    catalog: &'a TenantCatalog,
) -> Result<&'a CatalogDatasetEntry, AppError> {
    if metric.broken {
        return Err(AppError::Conflict("SCHEMA_BREAKING_CHANGE"));
    }
    let Some(dataset) = catalog.dataset_by_id(metric.dataset_id) else {
        return Err(AppError::NotFound("DATASET_NOT_FOUND"));
    };
    if is_metric_broken_for_dataset(metric, dataset) {
        return Err(AppError::Conflict("SCHEMA_BREAKING_CHANGE"));
    }
    Ok(dataset)
}

/// Compiles a single-metric [`MetricQuery`] (for its primary window) into a guarded [`CompiledMetricQuery`].
///
/// # Errors
/// Returns `SCHEMA_BREAKING_CHANGE`, `DATASET_NOT_FOUND`, `INVALID_ARGUMENT`, or `SQL_REJECTED`.
pub fn compile_metric_query(
    metric: &MetricDef,
    query: &MetricQuery,
    catalog: &TenantCatalog,
) -> Result<CompiledMetricQuery, AppError> {
    compile_metric_query_with_range(metric, query, query.time_range.as_ref(), catalog)
}

fn compile_metric_query_with_range(
    metric: &MetricDef,
    query: &MetricQuery,
    range_override: Option<&MetricTimeRange>,
    catalog: &TenantCatalog,
) -> Result<CompiledMetricQuery, AppError> {
    let dataset = check_metric_compatibility(metric, catalog)?;
    let (expr_ast, _, _) = inspect_sql_expression(&metric.expression, true)?;
    let resolved_dims = resolve_requested_dims(metric, dataset, &query.dimensions)?;

    let tc_info = resolve_metric_time_col(metric, dataset)?;
    if tc_info.is_none() && (range_override.is_some() || query.compare.is_some()) {
        return Err(AppError::bad(
            "INVALID_ARGUMENT",
            format!(
                "metric '{}' has no time_column for time_range or period comparison",
                metric.name
            ),
        ));
    }

    let mut projections = Vec::new();
    let (has_period, effective_grain) = if let Some((ref tc_col, _)) = tc_info {
        let grain = query.grain.unwrap_or(metric.default_grain);
        projections.push(format!(
            "date_trunc('{}', CAST({} AS TIMESTAMP)) AS \"period\"",
            rollup_grain_sql(grain),
            quote_ident(tc_col)
        ));
        (true, Some(grain))
    } else {
        (false, None)
    };

    let mut dim_names = Vec::with_capacity(resolved_dims.len());
    for d in &resolved_dims {
        projections.push(format!(
            "{} AS {}",
            quote_ident(&d.physical_col),
            quote_ident(&d.output_name)
        ));
        dim_names.push(d.output_name.clone());
    }
    projections.push(format!("({expr_ast}) AS \"value\""));

    let (where_sql, params) =
        build_single_metric_where(metric, dataset, query, range_override, tc_info.as_ref())?;
    let group_order_sql = build_metric_group_order(has_period, &resolved_dims);

    let raw_sql = format!(
        "SELECT {} FROM {}{}{}",
        projections.join(", "),
        quote_ident(&dataset.name),
        where_sql,
        group_order_sql
    );

    let guarded = guard(
        &raw_sql,
        catalog,
        &GuardOptions {
            max_rows: HARD_MAX_ROWS,
            allow_live: false,
            params,
        },
    )?;

    Ok(CompiledMetricQuery {
        raw_sql,
        guarded,
        has_period,
        effective_grain,
        dim_names,
    })
}

fn build_single_metric_where(
    metric: &MetricDef,
    dataset: &CatalogDatasetEntry,
    query: &MetricQuery,
    range_override: Option<&MetricTimeRange>,
    tc_info: Option<&(String, DataType)>,
) -> Result<(String, BTreeMap<String, serde_json::Value>), AppError> {
    let mut params = BTreeMap::new();
    let mut where_parts = Vec::new();

    let trimmed_filter = metric.filter_sql.trim();
    if !trimmed_filter.is_empty() {
        let (f_ast, _, _) = inspect_sql_expression(trimmed_filter, true)?;
        where_parts.push(format!("({f_ast})"));
    }

    if let Some(tr) = range_override {
        if tr.to <= tr.from {
            return Err(AppError::bad(
                "INVALID_ARGUMENT",
                "time_range.to must be greater than time_range.from",
            ));
        }
        if let Some((tc_col, tc_dt)) = tc_info {
            append_time_range_predicates(tc_col, *tc_dt, tr, &mut where_parts, &mut params);
        }
    }

    let ad_hoc_clauses = compile_filters_with_resolver(
        &query.filters,
        "__mf",
        |f| resolve_filter_col_for_metric(metric, dataset, f),
        &mut params,
    )?;
    where_parts.extend(ad_hoc_clauses);

    let where_sql = if where_parts.is_empty() {
        String::new()
    } else {
        format!(" WHERE {}", where_parts.join(" AND "))
    };
    Ok((where_sql, params))
}

fn build_metric_group_order(has_period: bool, resolved_dims: &[ResolvedMetricDim]) -> String {
    if !has_period && resolved_dims.is_empty() {
        return String::new();
    }
    let mut order_cols = Vec::new();
    if has_period {
        order_cols.push(String::from("\"period\" ASC"));
    }
    for d in resolved_dims {
        order_cols.push(format!("{} ASC NULLS LAST", quote_ident(&d.output_name)));
    }
    format!(" GROUP BY ALL ORDER BY {}", order_cols.join(", "))
}

/// Compiles and executes a single-metric [`MetricQuery`] against a [`TenantDb`] session (`05-STEP04` §04.5.2).
///
/// # Errors
/// Returns `PERMISSION_DENIED`, `SCHEMA_BREAKING_CHANGE`, `DATASET_NOT_FOUND`, `INVALID_ARGUMENT`,
/// `SQL_REJECTED`, `QUERY_TIMEOUT`, or `Database`.
pub async fn execute_metric_query(
    session: &TenantDb,
    catalog: &TenantCatalog,
    metric: &MetricDef,
    query: &MetricQuery,
    opts: MetricExecuteOptions,
) -> Result<MetricQueryResult, AppError> {
    if opts.reveal_pii && !opts.has_pii_raw_read {
        return Err(AppError::Forbidden("PERMISSION_DENIED"));
    }
    let primary_compiled = compile_metric_query(metric, query, catalog)?;
    let primary_out = session
        .execute_guarded(
            &primary_compiled.guarded,
            catalog,
            opts.timeout_ms,
            opts.reveal_pii,
            opts.has_pii_raw_read,
        )
        .await?;

    let Some(compare_mode) = query.compare else {
        return Ok(MetricQueryResult {
            metrics: vec![metric.name.clone()],
            columns: primary_out.result.columns,
            rows: primary_out.result.rows,
            sql: primary_out.result.sql,
            duration_ms: primary_out.result.duration_ms,
        });
    };

    if let Some(ref tr) = query.time_range {
        let grain = primary_compiled
            .effective_grain
            .unwrap_or(metric.default_grain);
        let shift = compute_range_shift(tr, compare_mode, grain)?;
        let cmp_compiled =
            compile_metric_query_with_range(metric, query, Some(&shift.shifted_range), catalog)?;
        let cmp_out = session
            .execute_guarded(
                &cmp_compiled.guarded,
                catalog,
                opts.timeout_ms,
                opts.reveal_pii,
                opts.has_pii_raw_read,
            )
            .await?;
        Ok(merge_compared_results(
            &metric.name,
            &primary_compiled,
            &primary_out.result,
            Some((&cmp_out.result, &shift)),
            compare_mode,
        ))
    } else {
        Ok(merge_compared_results(
            &metric.name,
            &primary_compiled,
            &primary_out.result,
            None,
            compare_mode,
        ))
    }
}

